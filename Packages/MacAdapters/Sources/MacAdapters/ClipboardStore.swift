import Foundation
import CSQLite

public struct ClipboardEntry: Identifiable, Sendable, Equatable {
    public let id: String
    public let text: String
    public let createdAt: Date
    public let pinned: Bool
    public let source: String
}

public struct ClipboardLimits: Sendable {
    public var retention: TimeInterval = 86400
    public var maxEntries: Int = 500
    public var maxItemBytes: Int = 1_048_576
    public var maxTotalBytes: Int = 33_554_432
    public init() {}
}

public enum ClipboardPolicy {
    public static func allows(types: [String], source: String?, excluded: Set<String>) -> Bool {
        let lower = types.map { $0.lowercased() }
        guard !lower.contains(where: { $0.contains("concealed") || $0.contains("transient") || $0.contains("autogenerated") }) else { return false }
        if let source, excluded.contains(source) { return false }
        return true
    }
}

public enum ClipboardDatabaseError: Error { case open, statement, incompatibleVersion }
private final class ClipboardConnection: @unchecked Sendable {
    let db: OpaquePointer
    init(url: URL) throws {
        var handle: OpaquePointer?
        guard sqlite3_open_v2(url.path, &handle, SQLITE_OPEN_CREATE | SQLITE_OPEN_READWRITE | SQLITE_OPEN_FULLMUTEX, nil) == SQLITE_OK, let handle else { if let handle { sqlite3_close(handle) }; throw ClipboardDatabaseError.open }
        db = handle
    }
    deinit { sqlite3_close(db) }
}

public actor ClipboardStore {
    private let connection: ClipboardConnection
    private let limits: ClipboardLimits
    public init(url: URL, limits: ClipboardLimits = ClipboardLimits()) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        connection = try ClipboardConnection(url: url); self.limits = limits
        let db = connection.db
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(db, "PRAGMA user_version", -1, &statement, nil) == SQLITE_OK else { throw ClipboardDatabaseError.statement }
        let version = sqlite3_step(statement) == SQLITE_ROW ? sqlite3_column_int(statement, 0) : -1
        sqlite3_finalize(statement)
        guard version >= 0 && version <= 1 else { throw ClipboardDatabaseError.incompatibleVersion }
        guard sqlite3_exec(db, "PRAGMA secure_delete=ON; CREATE TABLE IF NOT EXISTS clips(id TEXT PRIMARY KEY,body TEXT NOT NULL,created REAL NOT NULL,pinned INTEGER NOT NULL DEFAULT 0,source TEXT NOT NULL,bytes INTEGER NOT NULL); PRAGMA user_version=1;", nil, nil, nil) == SQLITE_OK else { throw ClipboardDatabaseError.statement }
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
    private func prepare(_ sql: String) throws -> OpaquePointer {
        var s: OpaquePointer?
        guard sqlite3_prepare_v2(connection.db, sql, -1, &s, nil) == SQLITE_OK, let s else { throw ClipboardDatabaseError.statement }; return s
    }
    private func bind(_ value: String, _ index: Int32, _ statement: OpaquePointer) {
        _ = value.withCString { sqlite3_bind_text(statement, index, $0, Int32(value.utf8.count), unsafeBitCast(-1, to: sqlite3_destructor_type.self)) }
    }
    public func insert(text: String, source: String, now: Date = Date()) throws {
        guard !text.isEmpty, text.utf8.count <= limits.maxItemBytes else { return }
        let s = try prepare("SELECT id FROM clips WHERE body=? LIMIT 1"); bind(text, 1, s)
        var existing: String?
        if sqlite3_step(s) == SQLITE_ROW { existing = String(cString: sqlite3_column_text(s, 0)) }; sqlite3_finalize(s)
        if let existing {
            let u = try prepare("UPDATE clips SET created=? WHERE id=?"); defer { sqlite3_finalize(u) }
            sqlite3_bind_double(u, 1, now.timeIntervalSince1970); bind(existing, 2, u)
            guard sqlite3_step(u) == SQLITE_DONE else { throw ClipboardDatabaseError.statement }
        } else {
            let q = try prepare("INSERT INTO clips(id,body,created,source,bytes) VALUES(?,?,?,?,?)"); defer { sqlite3_finalize(q) }
            bind(UUID().uuidString, 1, q); bind(text, 2, q); sqlite3_bind_double(q, 3, now.timeIntervalSince1970); bind(source, 4, q); sqlite3_bind_int64(q, 5, Int64(text.utf8.count))
            guard sqlite3_step(q) == SQLITE_DONE else { throw ClipboardDatabaseError.statement }
        }
        try prune(now: now)
    }
    public func prune(now: Date = Date()) throws {
        let s = try prepare("DELETE FROM clips WHERE pinned=0 AND created<?"); sqlite3_bind_double(s, 1, now.timeIntervalSince1970 - limits.retention)
        let result = sqlite3_step(s); sqlite3_finalize(s); guard result == SQLITE_DONE else { throw ClipboardDatabaseError.statement }
        while true {
            let count = try prepare("SELECT count(*),coalesce(sum(bytes),0) FROM clips")
            guard sqlite3_step(count) == SQLITE_ROW else { sqlite3_finalize(count); throw ClipboardDatabaseError.statement }
            let over = sqlite3_column_int64(count, 0) > limits.maxEntries || sqlite3_column_int64(count, 1) > limits.maxTotalBytes
            sqlite3_finalize(count); if !over { break }
            let del = try prepare("DELETE FROM clips WHERE id=(SELECT id FROM clips WHERE pinned=0 ORDER BY created ASC LIMIT 1)")
            let result = sqlite3_step(del); sqlite3_finalize(del)
            guard result == SQLITE_DONE else { throw ClipboardDatabaseError.statement }
            if sqlite3_changes(connection.db) == 0 { break }
        }
    }
    public func entries(query: String = "") throws -> [ClipboardEntry] {
        try prune()
        let s = try prepare("SELECT id,body,created,pinned,source FROM clips WHERE instr(lower(body),lower(?))>0 ORDER BY pinned DESC,created DESC LIMIT ?")
        defer { sqlite3_finalize(s) }; bind(query, 1, s); sqlite3_bind_int64(s, 2, Int64(limits.maxEntries))
        var rows: [ClipboardEntry] = []
        func text(_ column: Int32) -> String {
            guard let bytes = sqlite3_column_text(s, column) else { return "" }
            return String(decoding: UnsafeBufferPointer(start: bytes, count: Int(sqlite3_column_bytes(s, column))), as: UTF8.self)
        }
        while true {
            let status = sqlite3_step(s)
            if status == SQLITE_DONE { break }
            guard status == SQLITE_ROW else { throw ClipboardDatabaseError.statement }
            rows.append(ClipboardEntry(id: text(0), text: text(1), createdAt: Date(timeIntervalSince1970: sqlite3_column_double(s, 2)), pinned: sqlite3_column_int(s, 3) != 0, source: text(4)))
        }
        return rows
    }
    public func setPinned(id: String, pinned: Bool) throws {
        let s = try prepare("UPDATE clips SET pinned=? WHERE id=?"); defer { sqlite3_finalize(s) }
        sqlite3_bind_int(s, 1, pinned ? 1 : 0); bind(id, 2, s)
        guard sqlite3_step(s) == SQLITE_DONE else { throw ClipboardDatabaseError.statement }; try prune()
    }
    public func delete(id: String) throws {
        let s = try prepare("DELETE FROM clips WHERE id=?"); defer { sqlite3_finalize(s) }; bind(id, 1, s)
        guard sqlite3_step(s) == SQLITE_DONE else { throw ClipboardDatabaseError.statement }
    }
    public func clear() throws {
        guard sqlite3_exec(connection.db, "DELETE FROM clips; VACUUM;", nil, nil, nil) == SQLITE_OK else { throw ClipboardDatabaseError.statement }
    }
}
