import Foundation
import Testing
@testable import MacAdapters

/// 通过生产轮询路径检查惰性读取次序；来源是纯内存，不访问真实pasteboard正文。
@Suite(.serialized) @MainActor struct ClipboardMonitorTests {
    @Test func sensitiveTypesAndExcludedApplicationsAreFilteredBeforeReadingText() async throws {
        try await withMonitor { _, source, monitor in
            monitor.enabled = true
            for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
                source.types = ["public.utf8-plain-text", type]; source.write("Synthetic marked item")
                await monitor.poll()
            }
            source.types = ["public.utf8-plain-text"]; source.application = "synthetic.excluded"
            monitor.excludedApplications = ["synthetic.excluded"]; source.write("Synthetic excluded item")
            await monitor.poll()
            #expect(source.bodyReads == 0)
        }
    }

    @Test func changingCountOrSensitiveMetadataDuringReadPreventsStorage() async throws {
        for changeCount in [true, false] {
            try await withMonitor { store, source, monitor in
                monitor.enabled = true; source.write("Synthetic unstable item")
                source.onRead = { [weak source] in
                    guard let source else { return }
                    if changeCount { source.changeCount += 1 }
                    else { source.types.append("org.nspasteboard.ConcealedType") }
                }
                await monitor.poll()
                #expect(source.bodyReads == 1)
                let remaining = try await store.entries()
                #expect(remaining.isEmpty)
            }
        }
    }

    @Test func metadataChangeBeforeTextReadSkipsTheBody() async throws {
        try await withMonitor { store, source, monitor in
            monitor.enabled = true; source.write("Synthetic metadata race")
            source.onTypes = { [weak source] in source?.changeCount += 1 }
            await monitor.poll()
            let remaining = try await store.entries()
            #expect(source.bodyReads == 0 && remaining.isEmpty)
        }
    }

    @Test func pauseAndResumeDoNotBackfillSkippedChanges() async throws {
        try await withMonitor { store, source, monitor in
            monitor.enabled = true
            source.write("Synthetic first item"); await monitor.poll()
            monitor.enabled = false
            source.write("Synthetic paused item"); await monitor.poll()
            monitor.enabled = true; await monitor.poll()
            #expect(source.bodyReads == 1)
            source.write("Synthetic second item"); await monitor.poll()
            monitor.suspendCapture()
            source.write("Synthetic suspended item"); await monitor.poll()
            monitor.resumeCapture(); await monitor.poll()
            #expect(source.bodyReads == 2)
            source.write("Synthetic third item"); await monitor.poll()
            let remaining = try await store.entries()
            #expect(Set(remaining.map(\.text)) == ["Synthetic first item", "Synthetic second item", "Synthetic third item"])
        }
    }

    @Test func stopPreventsQueuedPollsAndRechecksAfterMaintenance() async throws {
        for duringMaintenance in [true, false] {
            try await withMonitor { store, source, monitor in
                monitor.enabled = true; source.write("Synthetic post-stop item")
                if duringMaintenance { monitor.onChange = { [weak monitor] in monitor?.stop() } }
                else { monitor.stop() }
                await monitor.poll()
                #expect(source.bodyReads == 0)
                let remaining = try await store.entries()
                #expect(remaining.isEmpty)
            }
        }
    }

    @Test func capacityRejectionIsReportedWithoutSuccessAndRecoversOnNextAcceptedItem() async throws {
        var limits = ClipboardLimits(); limits.maxItemBytes = 10; limits.maxTotalBytes = 10
        try await withMonitor(limits: limits) { store, source, monitor in
            try await store.insert(text: "PPPPPP", source: "synthetic")
            let row = try #require(await store.entries().first)
            try await store.setPinned(id: row.id, pinned: true)
            try await store.insert(text: "old", source: "synthetic")
            await monitor.poll() // 先完成独立的过期维护，不把它算作采集成功。
            var changes = 0, issues: [ClipboardRejection?] = []
            monitor.onChange = { changes += 1 }; monitor.onCaptureIssue = { issues.append($0) }
            monitor.enabled = true; source.write("12345"); await monitor.poll()
            #expect(changes == 0 && issues == [.capacity])
            #expect(Set(try await store.entries().map(\.text)) == ["PPPPPP", "old"])
            source.write("x"); await monitor.poll()
            #expect(changes == 1 && issues == [.capacity, nil])
            source.write("😃😃😃"); await monitor.poll()
            #expect(changes == 1 && issues == [.capacity, nil, .itemTooLarge])
        }
    }

    private func withMonitor(limits: ClipboardLimits = .init(), _ body: (ClipboardStore, SyntheticClipboardSource, ClipboardMonitor) async throws -> Void) async throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("KeyDock-Capture-" + UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let store = try ClipboardStore(url: directory.appendingPathComponent("clips.sqlite"), limits: limits)
        let source = SyntheticClipboardSource(), monitor = ClipboardMonitor(store: store, source: source)
        monitor.start(); defer { monitor.stop() }
        try await body(store, source, monitor)
    }
}

@MainActor private final class SyntheticClipboardSource: ClipboardCaptureSource {
    var changeCount = 0
    var types = ["public.utf8-plain-text"]
    var application: String? = "synthetic.editor"
    var availableTypes: [String] { let value = types; onTypes?(); return value }
    var sourceApplication: String? { application }
    var bodyReads = 0
    var onRead: (() -> Void)?
    var onTypes: (() -> Void)?
    private var body = ""
    func write(_ text: String) { body = text; changeCount += 1 }
    func readText() -> String? { bodyReads += 1; let value = body; onRead?(); return value }
}
